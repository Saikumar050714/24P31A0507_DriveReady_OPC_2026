from google.colab import userdata
import os
from langchain_groq import ChatGroq
from langchain_core.messages import SystemMessage, HumanMessage

os.environ["GROQ_API_KEY"] = userdata.get("GROQ_API_KEY")

llm = ChatGroq(
    model="openai/gpt-oss-120b",
    temperature=0
)

# Bakery Menu
MENU = {
    "plum cake": 500,
    "chocolate cake": 650,
    "cupcake": 80
}

# System Prompt
SYSTEM = """
You are a friendly assistant for Sweet Crumbs Home Bakery.

Rules:
1. Be polite and concise (under 60 words).
2. Orders require 24 hours advance notice.
3. Eggless options are available.
4. Never promise delivery times unless confirmed.
5. Use only the supplied menu and prices.
6. Never invent menu items or prices.
"""

# Chatbot Function
def bakery_chat(question):
    messages = [
        SystemMessage(content=SYSTEM + "\nMenu: " + str(MENU)),
        HumanMessage(content=question)
    ]

    response = llm.invoke(messages)
    return response.content

# Test Questions
questions = [
    "What is the price of a chocolate cake?",
    "Do you have eggless cakes?",
    "How much notice should I give before ordering?",
    "Can you guarantee delivery at 5 PM?"
]

# Display Responses
for question in questions:
    print("Customer:", question)
    print("Bot:", bakery_chat(question))
    print("-" * 60)

